export function isIconName(name: unknown): name is IconName {
  return typeof name === 'string' && (ICON_NAMES as readonly string[]).includes(name);
}

export function Icon({
  name,
  size = 20,
  strokeWidth = 1.9,
  className,
}: {
  name: unknown;
  size?: number;
  strokeWidth?: number;
  className?: string;
}) {
  const Cmp = isIconName(name) ? MAP[name] : Star;
  return <Cmp size={size} strokeWidth={strokeWidth} className={className} aria-hidden />;
}

export { MAP as ICON_MAP };
