#!/usr/bin/env node
/**
 * Build the production serverless function as ONE self-contained file.
 *
 * Why this exists: Vercel's Node builder compiles the entry it finds under
 * `api/`, but the entry used to `import '../../server/museProxy'` — a thin
 * relative import of a `.ts` file in another folder. When that link does not
 * survive into the deployed function, the result is not a helpful error: it is
 * `FUNCTION_INVOCATION_FAILED`, an opaque 500 at cold start, which is exactly
 * the "server error, no reason" this product refuses to show anyone.
 *
 * Bundling removes the link. The emitted function imports nothing but Node
 * built-ins, so it can fail only by our own logic — and that failure is caught
 * and turned into JSON with a real sentence.
 */
import { build } from 'esbuild';
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, relative } from 'node:path';

const OUT = 'api/muse/[...path].js';
const ROOT = process.cwd();
// --check builds in memory and compares with the committed artifact. The
// deployed function is a checked-in file, so a stale one would ship the old
// code — worse than a missing one, because nothing would look wrong.
const CHECK = process.argv.includes('--check');

mkdirSync(dirname(OUT), { recursive: true });

const result = await build({
  entryPoints: ['server/vercelEntry.ts'],
  outfile: OUT,
  write: !CHECK,
  bundle: true,
  platform: 'node',
  target: 'node20',
  // ESM, because package.json says "type": "module". Node resolves the emitted
  // `.js` as ESM and the default export is the handler.
  format: 'esm',
  // Node built-ins stay external; everything of ours is inlined.
  packages: 'bundle',
  external: ['node:*'],
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'warning',
  banner: {
    js: '// Generated by scripts/build-api.mjs — do not edit. Bundled from server/vercelEntry.ts.',
  },
  metafile: true,
});

const inputs = Object.keys(result.metafile.inputs).filter(
  (p) => !p.startsWith('node_modules/'),
);

if (CHECK) {
  const fresh = result.outputFiles?.[0]?.text ?? '';
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (!current) {
    console.error(`✗ api: ${OUT} is missing — run \`npm run build-api\`.`);
    process.exit(1);
  }
  if (current !== fresh) {
    console.error(
      `✗ api: ${OUT} is stale — the source changed but the deployed artifact did not.\n` +
        '  Run `npm run build-api` and commit the result.',
    );
    process.exit(1);
  }
  console.log(`✓ api: ${OUT} matches server/ (${inputs.length} modules)`);
  process.exit(0);
}

const bytes = statSync(OUT).size;
console.log(
  `✓ api: ${OUT} — ${(bytes / 1024).toFixed(1)} kB, ${inputs.length} inlined module${
    inputs.length === 1 ? '' : 's'
  }`,
);
for (const input of inputs) console.log(`   · ${relative(ROOT, input)}`);

// A relative import surviving into the bundle would defeat the whole point of
// this script, so treat it as a build failure rather than a surprise in prod.
for (const [file, meta] of Object.entries(result.metafile.outputs)) {
  const imports = meta.imports.filter((i) => i.external && !i.path.startsWith('node:'));
  if (imports.length) {
    console.error(
      `✗ api: ${file} still imports ${imports.map((i) => i.path).join(', ')} — the function must be self-contained.`,
    );
    process.exit(1);
  }
}
